// Scans assets/audio for native-speaker recordings and writes:
//   src/audio/clips.ts  – a static require() map (Metro needs static requires)
//   AUDIO_TODO.md       – every phrase and sentence still missing a recording
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const AUDIO = path.join(ROOT, 'assets', 'audio');
const EXT = ['.m4a', '.mp3', '.aac', '.wav'];

const files = existsSync(AUDIO) ? readdirSync(AUDIO).filter((f) => EXT.includes(path.extname(f).toLowerCase())).sort() : [];
const byId = new Map();
for (const f of files) {
  const id = path.basename(f, path.extname(f));
  if (!byId.has(id)) byId.set(id, f); // first extension wins (.m4a preferred alphabetically before .mp3)
}

const units = readdirSync(path.join(ROOT, 'content')).filter((d) => d.startsWith('unit-'));
const items = [];
for (const u of units) {
  const read = (f) => JSON.parse(readFileSync(path.join(ROOT, 'content', u, f), 'utf8'));
  for (const p of read('phrases.json')) items.push({ kind: 'phrase', unit: u, id: p.id, lg: p.lg });
  for (const s of read('sentences.json')) items.push({ kind: 'sentence', unit: u, id: s.id, lg: s.lg });
}
const known = new Set(items.map((i) => i.id));
const unknown = [...byId.keys()].filter((id) => !known.has(id));

const lines = [...byId.entries()].map(([id, f]) => `  '${id}': require('../../assets/audio/${f}'),`);
writeFileSync(
  path.join(ROOT, 'src', 'audio', 'clips.ts'),
  `// Generated by scripts/audio-manifest.mjs. Do not edit: add files to assets/audio and run \`npm run audio\`.\n` +
    `export const CLIPS: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);

const missing = items.filter((i) => !byId.has(i.id));
const md = [
  '# Audio to record',
  '',
  `Generated by \`npm run audio\`. ${byId.size} of ${items.length} recordings present.`,
  '',
  'Record each item with a native Luganda speaker, then save it as `assets/audio/<id>.m4a` (see README → Audio).',
  'Sentences with `{name}` are not needed: they contain the learner’s own name.',
  '',
  '| id | Luganda | kind |',
  '|---|---|---|',
  ...missing.filter((i) => !i.lg.includes('{name}')).map((i) => `| \`${i.id}\` | ${i.lg} | ${i.kind} |`),
  '',
];
if (unknown.length) md.push('## Files that match no phrase or sentence id', '', ...unknown.map((id) => `- \`${byId.get(id)}\``), '');
writeFileSync(path.join(ROOT, 'AUDIO_TODO.md'), md.join('\n'));
console.log(`audio: ${byId.size} clip(s), ${missing.length} missing${unknown.length ? `, ${unknown.length} unmatched file(s)` : ''}`);
