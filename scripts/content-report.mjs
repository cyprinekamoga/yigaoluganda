// Writes content/CONTENT_REPORT.md: what the course teaches and every item a native speaker should check.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (unit, f) => JSON.parse(readFileSync(path.join(ROOT, 'content', unit, f), 'utf8'));

const PARTS = [
  {
    dir: 'unit-1',
    title: 'Part 1: Absolute Foundations',
    intro: 'Part 1 follows the curriculum in the product requirements (12 chapters).',
    extra: [
      '- Words that only appear inside conversations: *oyagala* (do you want), *tulye* (let’s eat), *yingira* (come in), *ffene* (jackfruit), *lukumi* (one thousand), *laba* (look), *omanyi* (you know), *tukusanyukidde e Kampala*.',
      '- The PRD chapter titles *Okulagana* (goodbyes) and *Obubonero* (survival expressions) were kept as given; please confirm they fit.',
      '- Culture tips (kneeling, twin names, clans, eating customs) are written neutrally, but a Muganda reader should confirm the wording.',
    ],
  },
  {
    dir: 'unit-2',
    title: 'Part 2: Everyday Life',
    intro: 'Part 2 covers family, numbers, money and the market, food, time and days, directions, visiting a home and health.',
    extra: [
      '- Chapter titles written for this app: *Ab’omu Maka*, *Okubala*, *Ssente n’Akatale*, *Emmere n’Ebyokunywa*, *Ebiseera*, *Okutambula*, *Okukyala*, *Omubiri n’Obulamu*, *Okukyalira Jjajja*.',
      '- Words that only appear inside conversations: *Alabika bulungi* (she looks lovely), *basatu* (three, people), *ebiyembe* (mangoes), *ekibbo* (basket), *enkumi ttaano / nnya / ssatu* (5,000 / 4,000 / 3,000), *Komawo* (come back), *Oyagala kulya ki?*, *Ate okunywa?*, *Tulina* (we have), *Akatale kali wa?*, *okyuke ku ddyo*, *Kumpi wano*, *Oliwo?*, *Kiki ekikuluma?*, *Nja kukuwa eddagala*, *Enjala ekuluma?*, *Nkwagala nnyo*.',
      '- Time: the tip says the Luganda hour = clock hour minus six (essaawa emu = 7). Please confirm the wording, and the weekday names.',
      '- Culture tips (sibling words, family questions, luwombo, minibus taxis, being a guest, the village home) should be read by a Muganda reader.',
    ],
  },
];

const lines = [
  '# Content report',
  '',
  'Generated by `npm run report`. All Luganda was written for this app and **has not yet been reviewed by a native speaker**.',
  'Items marked below are the least certain; everything else still needs a read-through.',
  '',
];
for (const part of PARTS) {
  const chapters = read(part.dir, 'chapters.json');
  const phrases = Object.fromEntries(read(part.dir, 'phrases.json').map((p) => [p.id, p]));
  const sentences = read(part.dir, 'sentences.json');
  const dialogues = read(part.dir, 'dialogues.json');
  const known = { ...phrases };
  for (const other of PARTS) for (const p of read(other.dir, 'phrases.json')) known[p.id] ??= p;
  lines.push(
    `## ${part.title}`,
    '',
    part.intro,
    '',
    `**Totals:** ${Object.keys(phrases).length} phrases, ${sentences.length} sentences, ${dialogues.length} conversations, ${chapters.reduce((n, c) => n + c.lessons.length, 0)} lessons.`,
    '',
    '### Chapters',
    '',
    '| # | Luganda title | Title | Lessons | Phrases taught |',
    '|---|---|---|---|---|',
    ...chapters.map((c) => `| ${c.n} | ${c.lgTitle} | ${c.title.en} | ${c.lessons.length} | ${c.lessons.flatMap((l) => l.phrases).map((id) => known[id].lg).join(', ') || '(review)'} |`),
    '',
    '### Needs a native-speaker check',
    '',
    '| id | Luganda | Meaning | What to check |',
    '|---|---|---|---|',
    ...Object.values(phrases).filter((p) => p.check).map((p) => `| \`${p.id}\` | ${p.lg} | ${p.tr.en} | ${p.check} |`),
    ...sentences.filter((s) => s.check).map((s) => `| \`${s.id}\` | ${s.lg} | ${s.tr.en} | ${s.check} |`),
    '',
    '### Also worth checking',
    '',
    ...part.extra,
    '',
  );
}
writeFileSync(path.join(ROOT, 'content', 'CONTENT_REPORT.md'), lines.join('\n'));
console.log('wrote content/CONTENT_REPORT.md');
