// Writes content/CONTENT_REPORT.md: what the course teaches and every item a native speaker should check.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(path.join(ROOT, 'content', 'unit-1', f), 'utf8'));
const chapters = read('chapters.json');
const phrases = Object.fromEntries(read('phrases.json').map((p) => [p.id, p]));
const sentences = read('sentences.json');
const dialogues = read('dialogues.json');

const lines = [
  '# Content report: Unit 1',
  '',
  'Generated by `npm run report`. Unit 1 follows the curriculum in the product requirements (12 chapters).',
  'All Luganda was written for this app and **has not yet been reviewed by a native speaker**.',
  'Items marked below are the least certain; everything else still needs a read-through.',
  '',
  `**Totals:** ${Object.keys(phrases).length} phrases, ${sentences.length} sentences, ${dialogues.length} conversations, ${chapters.reduce((n, c) => n + c.lessons.length, 0)} lessons.`,
  '',
  '## Chapters',
  '',
  '| # | Luganda title | Title | Lessons | Phrases taught |',
  '|---|---|---|---|---|',
  ...chapters.map((c) => `| ${c.n} | ${c.lgTitle} | ${c.title.en} | ${c.lessons.length} | ${c.lessons.flatMap((l) => l.phrases).map((id) => phrases[id].lg).join(', ') || '(review)'} |`),
  '',
  '## Needs a native-speaker check',
  '',
  '| id | Luganda | Meaning | What to check |',
  '|---|---|---|---|',
  ...Object.values(phrases).filter((p) => p.check).map((p) => `| \`${p.id}\` | ${p.lg} | ${p.tr.en} | ${p.check} |`),
  ...sentences.filter((s) => s.check).map((s) => `| \`${s.id}\` | ${s.lg} | ${s.tr.en} | ${s.check} |`),
  '',
  '## Also worth checking',
  '',
  '- Words that only appear inside conversations: *oyagala* (do you want), *tulye* (let’s eat), *yingira* (come in), *ffene* (jackfruit), *lukumi* (one thousand), *laba* (look), *omanyi* (you know), *tukusanyukidde e Kampala*.',
  '- The PRD chapter titles *Okulagana* (goodbyes) and *Obubonero* (survival expressions) were kept as given; please confirm they fit.',
  '- Culture tips (kneeling, twin names, clans, eating customs) are written neutrally, but a Muganda reader should confirm the wording.',
  '',
];
writeFileSync(path.join(ROOT, 'content', 'CONTENT_REPORT.md'), lines.join('\n'));
console.log('wrote content/CONTENT_REPORT.md');
